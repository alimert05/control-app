package com.alicontrol.app.dashboard.profile

import com.alicontrol.app.dashboard.Dashboard
import com.alicontrol.app.dashboard.DashboardPage
import com.alicontrol.app.dashboard.DashboardWidget
import com.alicontrol.app.dashboard.EditRejection
import com.alicontrol.app.dashboard.EditResult
import com.alicontrol.app.dashboard.WidgetConfig
import com.alicontrol.app.dashboard.WidgetPlacement

/**
 * Every profile-level operation, as pure functions over immutable values — the
 * profile counterpart of [com.alicontrol.app.dashboard.DashboardEditor], and
 * built the same way: rejections are values ([EditResult.Rejected]), never
 * exceptions or half-applied state, and nothing here touches Android, storage or
 * live desktop state.
 *
 * What lives *inside* a profile (moving, resizing, adding and removing widgets;
 * creating, renaming, reordering and deleting pages) is **not** reimplemented
 * here: it is still `DashboardEditor` operating on the active profile's
 * dashboard, and the result is stored back with [replaceDashboard]. This object
 * only manages the set of profiles.
 *
 * Every operation returns a new [ProfileCollection] and changes *only* what it
 * names — in particular, no operation but [replaceDashboard] and [resetProfile]
 * ever produces a different dashboard, and those two change a single profile's.
 */
object ProfileEditor {

    const val MAX_PROFILE_NAME_LENGTH = 24

    /** A collection with one profile added, and that profile (so the caller can switch to it). */
    data class Added(val collection: ProfileCollection, val profile: DashboardProfile)

    // -- selection and layout --

    /** Makes [profileId] the last selected (active) profile. Selecting the current one is a no-op success. */
    fun select(collection: ProfileCollection, profileId: String): EditResult<ProfileCollection> {
        val profile = collection.profile(profileId)
        if (profile == null || !profile.isValid()) return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        if (collection.lastSelectedProfileId == profileId) return EditResult.Success(collection)
        return EditResult.Success(collection.copy(lastSelectedProfileId = profileId))
    }

    /**
     * Stores an edited dashboard as [profileId]'s own — how every `DashboardEditor`
     * result reaches a profile. An invalid dashboard is refused, so no invalid layout
     * can ever be persisted.
     */
    fun replaceDashboard(collection: ProfileCollection, profileId: String, dashboard: Dashboard): EditResult<ProfileCollection> {
        val profile = collection.profile(profileId) ?: return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        if (!dashboard.isValid()) return EditResult.Rejected(EditRejection.INVALID_LAYOUT)
        return EditResult.Success(collection.withProfile(profile.copy(dashboard = dashboard)))
    }

    // -- create / duplicate --

    /**
     * Adds a custom profile with an empty (but valid) dashboard at the end of the order.
     * The id is generated by [newId] — random, never derived from [name].
     */
    fun createProfile(
        collection: ProfileCollection,
        name: String,
        newId: () -> String = ProfileIds::generate
    ): EditResult<Added> {
        val cleanName = sanitizeName(name) ?: return EditResult.Rejected(EditRejection.INVALID_NAME)
        return EditResult.Success(append(collection, cleanName, emptyDashboard(), newId))
    }

    /**
     * Adds a custom profile that starts as an independent copy of [sourceId] — named
     * "<name> Copy" (numbered if that is taken). The dashboard is deep-copied
     * ([deepCopy]), so the two profiles share no state and editing one can never touch
     * the other. Only the profile id is regenerated: page and widget ids need to be
     * unique within their own dashboard, which the copy already satisfies.
     * Duplicating a built-in profile yields a custom one.
     */
    fun duplicateProfile(
        collection: ProfileCollection,
        sourceId: String,
        newId: () -> String = ProfileIds::generate
    ): EditResult<Added> {
        val source = collection.profile(sourceId) ?: return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        val name = uniqueCopyName(source.name, collection.profiles.map { it.name }.toSet())
        return EditResult.Success(append(collection, name, deepCopy(source.dashboard), newId))
    }

    // -- rename / reorder / default --

    /** Renames a profile. Its id — what persistence and the startup policy key off — never changes. */
    fun renameProfile(collection: ProfileCollection, profileId: String, name: String): EditResult<ProfileCollection> {
        val profile = collection.profile(profileId) ?: return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        val cleanName = sanitizeName(name) ?: return EditResult.Rejected(EditRejection.INVALID_NAME)
        return EditResult.Success(collection.withProfile(profile.copy(name = cleanName)))
    }

    /**
     * Moves a profile [offset] positions in the display order (-1 = earlier, +1 = later),
     * clamped at the ends — moving the first profile earlier is a no-op success, exactly
     * like `DashboardEditor.movePage`.
     */
    fun moveProfile(collection: ProfileCollection, profileId: String, offset: Int): EditResult<ProfileCollection> {
        val ordered = collection.orderedProfiles.toMutableList()
        val index = ordered.indexOfFirst { it.id == profileId }
        if (index < 0) return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        val target = (index + offset).coerceIn(0, ordered.size - 1)
        if (target == index) return EditResult.Success(collection)
        val profile = ordered.removeAt(index)
        ordered.add(target, profile)
        // Renumber from the new list positions directly (see DashboardEditor.movePage).
        return EditResult.Success(collection.copy(profiles = ordered.mapIndexed { position, p -> p.copy(order = position) }))
    }

    /** Marks [profileId] as the startup default — the fallback when the last selected profile cannot be restored. */
    fun setStartupDefault(collection: ProfileCollection, profileId: String): EditResult<ProfileCollection> {
        if (collection.profile(profileId) == null) return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        return EditResult.Success(collection.copy(defaultProfileId = profileId))
    }

    // -- reset / delete --

    /**
     * Restores one profile's layout and nothing else: a built-in profile gets its shipped
     * template, a custom one an empty valid dashboard (no "original source" is tracked for
     * a duplicate — the result stays predictable). The profile's id, name and position,
     * every other profile, and all live state are untouched.
     */
    fun resetProfile(collection: ProfileCollection, profileId: String): EditResult<ProfileCollection> {
        val profile = collection.profile(profileId) ?: return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        val dashboard = BuiltInProfiles.dashboardFor(profileId) ?: emptyDashboard()
        return EditResult.Success(collection.withProfile(profile.copy(dashboard = dashboard)))
    }

    /**
     * Deletes a custom profile. Built-in profiles are refused (they can be reset instead),
     * and so is the last remaining profile, so the collection can never end up empty.
     * Other profiles are not modified. If the deleted profile was the selected one, the
     * selection falls back through the startup policy ([ProfileCollection.resolve]); if it
     * was the startup default, that falls back to the built-in default.
     */
    fun deleteProfile(collection: ProfileCollection, profileId: String): EditResult<ProfileCollection> {
        val profile = collection.profile(profileId) ?: return EditResult.Rejected(EditRejection.UNKNOWN_PROFILE)
        if (profile.builtIn || ProfileIds.isBuiltIn(profile.id)) return EditResult.Rejected(EditRejection.BUILT_IN_PROTECTED)
        if (collection.profiles.size <= 1) return EditResult.Rejected(EditRejection.LAST_PROFILE)
        return EditResult.Success(collection.copy(profiles = collection.profiles.filterNot { it.id == profileId }).normalized())
    }

    // -- values --

    /** Trimmed, length-capped name, or null when the user typed nothing usable. */
    fun sanitizeName(name: String): String? {
        val trimmed = name.trim()
        if (trimmed.isEmpty()) return null
        return trimmed.take(MAX_PROFILE_NAME_LENGTH).trimEnd()
    }

    /** What "empty" means for a new or cleared custom profile: one blank page, so the dashboard is still valid. */
    fun emptyDashboard(): Dashboard =
        Dashboard(listOf(DashboardPage(id = "page_custom_1", name = "Page 1", order = 0, widgets = emptyList())))

    /**
     * A [Dashboard] with no object shared with [dashboard]: every page, widget, placement
     * and config — including the lists inside them — is rebuilt. The model is immutable
     * already, but a `List` can still be backed by a shared mutable one; copying
     * explicitly makes "no shared mutable state" a guarantee rather than a property of
     * how the caller built the original.
     */
    fun deepCopy(dashboard: Dashboard): Dashboard = Dashboard(
        dashboard.pages.map { page ->
            DashboardPage(page.id, page.name, page.order, page.widgets.map(::copyWidget))
        }
    )

    private fun copyWidget(widget: DashboardWidget): DashboardWidget = DashboardWidget(
        id = widget.id,
        type = widget.type,
        placement = with(widget.placement) { WidgetPlacement(x, y, width, height) },
        config = copyConfig(widget.config)
    )

    private fun copyConfig(config: WidgetConfig): WidgetConfig = when (config) {
        is WidgetConfig.Action -> WidgetConfig.Action(config.actionId)
        is WidgetConfig.ActionGroup -> WidgetConfig.ActionGroup(config.actionIds.toList())
        is WidgetConfig.Metric -> WidgetConfig.Metric(config.label)
        is WidgetConfig.Gauge -> WidgetConfig.Gauge(config.label)
        is WidgetConfig.Clock -> WidgetConfig.Clock(config.showDate)
        is WidgetConfig.DailyOverview -> WidgetConfig.DailyOverview(config.locationLabel)
        is WidgetConfig.Media -> WidgetConfig.Media(config.previousActionId, config.playPauseActionId, config.nextActionId)
        is WidgetConfig.Slider -> WidgetConfig.Slider(config.label, config.actionIds.toList())
        is WidgetConfig.Shortcut -> WidgetConfig.Shortcut(config.label, config.destination)
    }

    // -- helpers --

    private fun append(collection: ProfileCollection, name: String, dashboard: Dashboard, newId: () -> String): Added {
        val profile = DashboardProfile(
            id = freshId(collection, newId),
            name = name,
            order = (collection.profiles.maxOfOrNull { it.order } ?: -1) + 1,
            builtIn = false,
            dashboard = dashboard
        )
        // Normalizing renumbers `order` to 0..n-1 with the new profile last.
        val updated = collection.copy(profiles = collection.orderedProfiles + profile).normalized()
        return Added(updated, updated.profile(profile.id) ?: profile)
    }

    /**
     * An id nobody else has and no built-in profile owns. A generator that keeps handing
     * back a taken id (only conceivable in a test) still terminates: after a few tries a
     * counter is appended.
     */
    private fun freshId(collection: ProfileCollection, newId: () -> String): String {
        val taken = { id: String -> id.isBlank() || ProfileIds.isBuiltIn(id) || collection.profile(id) != null }
        repeat(MAX_ID_ATTEMPTS) {
            val candidate = newId()
            if (!taken(candidate)) return candidate
        }
        val base = newId().ifBlank { "custom" }
        var counter = 1
        while (taken("${base}_$counter")) counter++
        return "${base}_$counter"
    }

    private fun uniqueCopyName(sourceName: String, existing: Set<String>): String {
        val suffix = " Copy"
        fun candidate(number: Int): String {
            val tail = if (number == 1) suffix else "$suffix $number"
            return sourceName.take(MAX_PROFILE_NAME_LENGTH - tail.length).trimEnd() + tail
        }
        var number = 1
        while (candidate(number) in existing) number++
        return candidate(number)
    }

    private const val MAX_ID_ATTEMPTS = 16
}
